CREATE OR REPLACE TABLE EXERCISE_DB.PUBLIC.CUSTOMER 
(
    ID          INT,
    first_name  VARCHAR,
    last_name   VARCHAR,
    email       VARCHAR,
    age         INT,
    city        VARCHAR
);

CREATE OR REPLACE STAGE EXERCISE_DB.PUBLIC.AWS_STAGE_FILEFORMAT
    URL = 's3://snowflake-assignments-mc/fileformat/';

CREATE OR REPLACE FILE FORMAT EXERCISE_DB.PUBLIC.FILE_FORMAT_CSV_PIPE
TYPE = CSV
FIELD_DELIMITER = '|'
SKIP_HEADER = 1;

DESC STAGE EXERCISE_DB.PUBLIC.AWS_STAGE_FILEFORMAT;

LIST @EXERCISE_DB.PUBLIC.AWS_STAGE_FILEFORMAT;

COPY INTO EXERCISE_DB.PUBLIC.CUSTOMER 
    FROM @EXERCISE_DB.PUBLIC.AWS_STAGE_FILEFORMAT
        FILE_FORMAT= ( format_name = EXERCISE_DB.PUBLIC.FILE_FORMAT_CSV_PIPE );

-- alternative
COPY INTO EXERCISE_DB.PUBLIC.CUSTOMER
    FROM @EXERCISE_DB.PUBLIC.AWS_STAGE_FILEFORMAT
      FILE_FORMAT = EXERCISE_DB.PUBLIC.FILE_FORMAT_CSV_PIPE;

SELECT COUNT(*) FROM EXERCISE_DB.PUBLIC.CUSTOMER;