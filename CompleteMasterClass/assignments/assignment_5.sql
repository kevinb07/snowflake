USE DATABASE EXERCISE_DB;

CREATE OR REPLACE TABLE EXERCISE_DB.PUBLIC.EMPLOYEES
(
CUSTOMER_ID INT,
FIRST_NAME  VARCHAR(50),
LAST_NAME   VARCHAR(50),
EMAIL       VARCHAR(50),
AGE         INT,
DEPARTMENT  VARCHAR(50)
);

CREATE OR REPLACE STAGE EXERCISE_DB.PUBLIC.AWS_COPYOPTIONS
    URL='s3://snowflake-assignments-mc/copyoptions/example1';

LIST @EXERCISE_DB.PUBLIC.AWS_COPYOPTIONS;

CREATE OR REPLACE FILE FORMAT EXERCISE_DB.PUBLIC.FILE_FORMAT_CSV
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1;

COPY INTO EXERCISE_DB.PUBLIC.EMPLOYEES
    FROM @EXERCISE_DB.PUBLIC.AWS_COPYOPTIONS
    FILE_FORMAT = EXERCISE_DB.PUBLIC.FILE_FORMAT_CSV
    VALIDATION_MODE = RETURN_ERRORS;

COPY INTO EXERCISE_DB.PUBLIC.EMPLOYEES
    FROM @EXERCISE_DB.PUBLIC.AWS_COPYOPTIONS
    FILE_FORMAT = EXERCISE_DB.PUBLIC.FILE_FORMAT_CSV
    ON_ERROR = CONTINUE;