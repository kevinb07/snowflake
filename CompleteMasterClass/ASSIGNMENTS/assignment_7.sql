USE DATABASE EXERCISE_DB;

CREATE OR REPLACE STAGE EXERCISE_DB.PUBLIC.AWS_JSON
 URL = 's3://snowflake-assignments-mc/unstructureddata/';

LIST @EXERCISE_DB.PUBLIC.AWS_JSON;

CREATE OR REPLACE FILE FORMAT EXERCISE_DB.PUBLIC.FILE_FORMAT_JSON
 TYPE = JSON;

CREATE OR REPLACE TABLE EXERCISE_DB.PUBLIC.JSON_RAW
(
    RAW VARIANT
);

COPY INTO EXERCISE_DB.PUBLIC.JSON_RAW 
    FROM @EXERCISE_DB.PUBLIC.AWS_JSON 
    FILE_FORMAT = EXERCISE_DB.PUBLIC.FILE_FORMAT_JSON;

SELECT * FROM EXERCISE_DB.PUBLIC.JSON_RAW;