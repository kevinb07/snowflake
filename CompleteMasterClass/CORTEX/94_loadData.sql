-- 01_load_data.sql
-- Goal: Load CSV data from the internal stage into RAW tables,
-- then build an AI-ready text table (CONCATENATED_REVIEWS).

USE ROLE SYSADMIN;
USE WAREHOUSE TB_VOC_WH;

-- Load CSVs into RAW tables (paths must match the folder structure in the stage)
COPY INTO TB_VOC.RAW_POS.MENU
FROM @TB_VOC.PUBLIC.LOAD_STAGE/raw_pos/menu/
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO TB_VOC.RAW_POS.TRUCK
FROM @TB_VOC.PUBLIC.LOAD_STAGE/raw_pos/truck/
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO TB_VOC.RAW_POS.ORDER_HEADER
FROM @TB_VOC.PUBLIC.LOAD_STAGE/raw_pos/order_header/
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO TB_VOC.RAW_SUPPORT.TRUCK_REVIEWS
FROM @TB_VOC.PUBLIC.LOAD_STAGE/raw_support/truck_reviews/
ON_ERROR = 'ABORT_STATEMENT';

-- Build the table used for LLM Q&A (one text blob per brand)
USE SCHEMA TB_VOC.ANALYTICS;

CREATE OR REPLACE TABLE CONCATENATED_REVIEWS AS
WITH ranked AS (
  SELECT
    TRUCK_BRAND_NAME,
    REVIEW,
    REVIEW_ID,
    ROW_NUMBER() OVER (PARTITION BY TRUCK_BRAND_NAME ORDER BY REVIEW_ID) AS RN
  FROM TRUCK_REVIEWS_V
),
filtered AS (
  SELECT TRUCK_BRAND_NAME, REVIEW
  FROM ranked
  WHERE RN <= 20
),
agg AS (
  SELECT
    TRUCK_BRAND_NAME,
    ARRAY_AGG(REVIEW) AS ALL_REVIEWS
  FROM filtered
  GROUP BY TRUCK_BRAND_NAME
)
SELECT
  TRUCK_BRAND_NAME,
  ARRAY_TO_STRING(ALL_REVIEWS, ' ') AS ALL_REVIEWS_TEXT
FROM agg;

-- Quick validation (if harmonized_view is 0, joins/keys are wrong)
SELECT 'menu' AS object_name, COUNT(*) FROM TB_VOC.RAW_POS.MENU
UNION ALL
SELECT 'truck', COUNT(*) FROM TB_VOC.RAW_POS.TRUCK
UNION ALL
SELECT 'order_header', COUNT(*) FROM TB_VOC.RAW_POS.ORDER_HEADER
UNION ALL
SELECT 'truck_reviews', COUNT(*) FROM TB_VOC.RAW_SUPPORT.TRUCK_REVIEWS
UNION ALL
SELECT 'harmonized_view', COUNT(*) FROM TB_VOC.HARMONIZED.TRUCK_REVIEWS_V
UNION ALL
SELECT 'concatenated_reviews', COUNT(*) FROM TB_VOC.ANALYTICS.CONCATENATED_REVIEWS;

SELECT '01_load_data.sql complete' AS NOTE;