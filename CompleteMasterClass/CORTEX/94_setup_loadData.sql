-- 00_setup_infra.sql
-- Goal: Create all Snowflake objects (DB, schemas, tables, views, stages).
-- This script does NOT load data yet.

USE ROLE SYSADMIN;

-- Create the project database
CREATE OR REPLACE DATABASE TB_VOC;

-- Create schemas (layers)
CREATE OR REPLACE SCHEMA TB_VOC.PUBLIC;       -- shared objects (file format, load stage)
CREATE OR REPLACE SCHEMA TB_VOC.RAW_POS;      -- raw structured data (POS-like)
CREATE OR REPLACE SCHEMA TB_VOC.RAW_SUPPORT;  -- raw unstructured text data (reviews)
CREATE OR REPLACE SCHEMA TB_VOC.HARMONIZED;   -- business-ready joins
CREATE OR REPLACE SCHEMA TB_VOC.ANALYTICS;    -- analytics/AI-ready outputs
CREATE OR REPLACE SCHEMA TB_VOC.MEDIA;        -- images/audio storage + mapping tables

-- Small warehouse for demos (cheap + auto-suspends)
CREATE OR REPLACE WAREHOUSE TB_VOC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  WAREHOUSE_TYPE = 'STANDARD'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- CSV file format (we assume 1 header row in the CSV files)
CREATE OR REPLACE FILE FORMAT TB_VOC.PUBLIC.CSV_FF
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('', 'NULL', 'null');

-- Internal stage for CSV uploads (students upload the folders here)
CREATE OR REPLACE STAGE TB_VOC.PUBLIC.LOAD_STAGE
  FILE_FORMAT = TB_VOC.PUBLIC.CSV_FF
  DIRECTORY = (ENABLE = TRUE);

-- Internal stages for images and audio (students upload files here)
CREATE OR REPLACE STAGE TB_VOC.MEDIA.IMAGES
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE);

CREATE OR REPLACE STAGE TB_VOC.MEDIA.AUDIO
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE);

-- RAW tables (loaded from CSV)
CREATE OR REPLACE TABLE TB_VOC.RAW_POS.MENU
(
  MENU_ID NUMBER(19,0),
  MENU_TYPE_ID NUMBER(38,0),
  MENU_TYPE STRING,
  TRUCK_BRAND_NAME STRING,
  MENU_ITEM_ID NUMBER(38,0),
  MENU_ITEM_NAME STRING,
  ITEM_CATEGORY STRING,
  ITEM_SUBCATEGORY STRING,
  COST_OF_GOODS_USD NUMBER(38,4),
  SALE_PRICE_USD NUMBER(38,4),
  MENU_ITEM_HEALTH_METRICS_OBJ VARIANT  -- JSON-like data
);

CREATE OR REPLACE TABLE TB_VOC.RAW_POS.TRUCK
(
  TRUCK_ID NUMBER(38,0),
  MENU_TYPE_ID NUMBER(38,0),
  PRIMARY_CITY STRING,
  REGION STRING,
  ISO_REGION STRING,
  COUNTRY STRING,
  ISO_COUNTRY_CODE STRING,
  FRANCHISE_FLAG NUMBER(38,0),
  YEAR NUMBER(38,0),
  MAKE STRING,
  MODEL STRING,
  EV_FLAG NUMBER(38,0),
  FRANCHISE_ID NUMBER(38,0),
  TRUCK_OPENING_DATE DATE
);

CREATE OR REPLACE TABLE TB_VOC.RAW_POS.ORDER_HEADER
(
  ORDER_ID NUMBER(38,0),
  TRUCK_ID NUMBER(38,0),
  LOCATION_ID FLOAT,
  CUSTOMER_ID NUMBER(38,0),
  DISCOUNT_ID STRING,
  SHIFT_ID NUMBER(38,0),
  SHIFT_START_TIME TIME(9),
  SHIFT_END_TIME TIME(9),
  ORDER_CHANNEL STRING,
  ORDER_TS TIMESTAMP_NTZ(9),
  SERVED_TS STRING,
  ORDER_CURRENCY STRING,
  ORDER_AMOUNT NUMBER(38,4),
  ORDER_TAX_AMOUNT STRING,
  ORDER_DISCOUNT_AMOUNT STRING,
  ORDER_TOTAL NUMBER(38,4)
);

CREATE OR REPLACE TABLE TB_VOC.RAW_SUPPORT.TRUCK_REVIEWS
(
  ORDER_ID NUMBER(38,0),
  LANGUAGE STRING,   -- e.g. en, es, fr, de
  SOURCE STRING,     -- e.g. google, yelp
  REVIEW STRING,
  REVIEW_ID NUMBER(18,0)
);

-- Harmonized view: join reviews with business context (brand, city, date, customer)
CREATE OR REPLACE VIEW TB_VOC.HARMONIZED.TRUCK_REVIEWS_V AS
SELECT DISTINCT
  r.REVIEW_ID,
  r.ORDER_ID,
  oh.TRUCK_ID,
  r.LANGUAGE,
  r.SOURCE,
  r.REVIEW,
  t.PRIMARY_CITY,
  oh.CUSTOMER_ID,
  TO_DATE(oh.ORDER_TS) AS DATE,
  m.TRUCK_BRAND_NAME
FROM TB_VOC.RAW_SUPPORT.TRUCK_REVIEWS r
JOIN TB_VOC.RAW_POS.ORDER_HEADER oh
  ON oh.ORDER_ID = r.ORDER_ID
JOIN TB_VOC.RAW_POS.TRUCK t
  ON t.TRUCK_ID = oh.TRUCK_ID
JOIN TB_VOC.RAW_POS.MENU m
  ON m.MENU_TYPE_ID = t.MENU_TYPE_ID;

-- Analytics view: re-expose the curated data for analysts/AI demos
CREATE OR REPLACE VIEW TB_VOC.ANALYTICS.TRUCK_REVIEWS_V AS
SELECT * FROM TB_VOC.HARMONIZED.TRUCK_REVIEWS_V;

-- Media mapping tables (we store file paths after you upload images/audio)
CREATE OR REPLACE TABLE TB_VOC.MEDIA.IMAGE_TABLE
(
  TRUCK_BRAND_NAME STRING,
  IMAGE_PATH STRING,  -- example: 'images/fiesta_taco_01.jpg'
  CAPTION STRING
);

CREATE OR REPLACE TABLE TB_VOC.MEDIA.AUDIO_TABLE
(
  TRUCK_BRAND_NAME STRING,
  AUDIO_PATH STRING,  -- example: 'audio/fiesta_taco_01.mp3'
  NOTES STRING
);

SELECT '00_setup_infra.sql complete' AS NOTE;