// Create a stored procedure
USE TASK_DB;

SELECT * FROM CUSTOMERS;



CREATE OR REPLACE PROCEDURE CUSTOMERS_INSERT_PROCEDURE (CREATE_DATE varchar)
    RETURNS STRING NOT NULL
    LANGUAGE JAVASCRIPT
    AS
        $$
        var sql_command = 'INSERT INTO CUSTOMERS(CREATE_DATE) VALUES(:1);'
        snowflake.execute(
            {
            sqlText: sql_command,
            binds: [CREATE_DATE]
            });
        return "Successfully executed.";
        $$;
        
        
    
CREATE OR REPLACE TASK CUSTOMER_TASKS_PROCEDURE
WAREHOUSE = KB_DWH
SCHEDULE = '1 MINUTE'
AS CALL  CUSTOMERS_INSERT_PROCEDURE (CURRENT_TIMESTAMP);


SHOW TASKS;

ALTER TASK CUSTOMER_TASKS_PROCEDURE RESUME;
ALTER TASK CUSTOMER_TASKS_PROCEDURE SUSPEND;


SELECT * FROM CUSTOMERS ORDER BY CUSTOMER_ID DESC;

-- cleanup
DROP PROCEDURE IF EXISTS CUSTOMERS_INSERT_PROCEDURE (varchar);
DROP TASK IF EXISTS CUSTOMER_TASKS_PROCEDURE;